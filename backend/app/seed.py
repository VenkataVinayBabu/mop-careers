def make_notes_pdf(day_number: int, topic: str, batch_name: str) -> str:
    """Write a placeholder notes PDF for a taught day and return its filename.

    Without this, no seeded day has notes and the student's "Notes PDF" button
    never appears — leaving that path invisible in the demo.
    """
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.pdfgen import canvas

    filename = f"seed_{batch_name.lower()}_day{day_number}.pdf"
    path = NOTES_DIR / filename

    c = canvas.Canvas(str(path), pagesize=A4)
    width, height = A4

    c.setFillColorRGB(0.043, 0.118, 0.275)   # navy #0B1E46
    c.rect(0, height - 28 * mm, width, 28 * mm, stroke=0, fill=1)
    c.setFillColorRGB(1, 1, 1)
    c.setFont("Helvetica-Bold", 18)
    c.drawString(20 * mm, height - 18 * mm, "MOP CAREERS")

    c.setFillColorRGB(0.043, 0.118, 0.275)
    c.setFont("Helvetica-Bold", 15)
    c.drawString(20 * mm, height - 45 * mm, f"Day {day_number} - {topic}")

    c.setFillColorRGB(0, 0.596, 0.616)       # teal #00989D
    c.setFont("Helvetica", 11)
    c.drawString(20 * mm, height - 53 * mm, f"Batch {batch_name}  |  Python Full Stack")

    c.setFillColorRGB(0.2, 0.2, 0.2)
    c.setFont("Helvetica", 10.5)
    lines = [
        "",
        "These are placeholder class notes generated by the seed script.",
        "Your instructor will replace them with the real notes for this session.",
        "",
        "In this session we cover:",
        f"  -  An introduction to {topic.lower()}",
        "  -  Worked examples written live in class",
        "  -  Common mistakes and how to avoid them",
        "  -  Practice exercises to complete before the next class",
    ]
    y = height - 68 * mm
    for line in lines:
        c.drawString(20 * mm, y, line)
        y -= 6 * mm

    c.setFont("Helvetica-Oblique", 8.5)
    c.setFillColorRGB(0.5, 0.5, 0.5)
    c.drawString(20 * mm, 15 * mm, "MOP Careers - Python Full Stack programme")

    c.showPage()
    c.save()
    return filename


def upsert_user(db: Session, *, name: str, email: str, password: str, role: str,
                phone: str | None = None, must_change: bool = False,
                yoe_it: float | None = None, batch_id: int | None = None) -> User:
    user = db.scalar(select(User).where(User.email == email))
    if user is None:
        user = User(email=email)
        db.add(user)
    user.name = name
    user.phone = phone
    user.role = role
    user.password_hash = hash_password(password)
    user.must_change_password = must_change
    user.is_blocked = False
    user.yoe_it = yoe_it
    user.batch_id = batch_id
    db.flush()
    return user


def reset_data(db: Session) -> None:
    """Drop all seeded rows. Destructive — only runs behind --reset.

    Order matters: children before parents.
    """
    db.execute(delete(InterviewRound))
    db.execute(delete(Application))
    db.execute(delete(Company))
    db.execute(delete(FeePayment))
    db.execute(delete(FeeRecord))
    db.execute(delete(Attendance))
    db.execute(delete(PasswordResetToken))
    db.execute(delete(CurriculumDay))
    db.execute(delete(TeacherBatch))
    db.execute(delete(Milestone))
    db.execute(delete(User))
    db.execute(delete(Batch))
    db.commit()
    print("  Cleared existing data.")


