def seed_phase2(db: Session, students: list[User], start: date) -> None:
    """Fees and placements demo data."""
    # --- fees ---------------------------------------------------------
    payments_made = 0
    for student, plan in zip(students, FEE_PLAN):
        record = db.scalar(select(FeeRecord).where(FeeRecord.student_id == student.id))
        if record is None:
            record = FeeRecord(student_id=student.id)
            db.add(record)
        record.total_fee = TOTAL_FEE
        record.notes = "Standard Python Full Stack programme fee."
        db.flush()

        existing = db.scalar(
            select(func.count(FeePayment.id)).where(FeePayment.student_id == student.id)
        )
        if existing:
            continue
        for amount, offset, mode in plan:
            db.add(
                FeePayment(
                    student_id=student.id,
                    amount=amount,
                    paid_on=start + timedelta(days=offset),
                    mode=mode,
                    reference=f"REF{student.id:03d}{offset:03d}",
                )
            )
            payments_made += 1

    fully_paid = sum(1 for p in FEE_PLAN if sum(a for a, _, _ in p) >= TOTAL_FEE)
    print(f"  Fees: {len(students)} records at {TOTAL_FEE:,.0f}, {payments_made} payments "
          f"({fully_paid} paid in full)")

    # --- companies ----------------------------------------------------
    companies: list[Company] = []
    for name, website, location in COMPANIES:
        c = db.scalar(select(Company).where(Company.name == name))
        if c is None:
            c = Company(name=name, website=website, location=location)
            db.add(c)
            db.flush()
        companies.append(c)

    # --- applications + rounds ----------------------------------------
    created = 0
    for s_idx, c_idx, role, status_, package, rounds in APPLICATIONS:
        student = students[s_idx]
        company = companies[c_idx]
        existing = db.scalar(
            select(Application).where(
                Application.student_id == student.id,
                Application.company_id == company.id,
                Application.role_title == role,
            )
        )
        if existing:
            continue

        app = Application(
            student_id=student.id,
            company_id=company.id,
            role_title=role,
            status=status_,
            package_lpa=package,
            applied_on=start + timedelta(days=30 + s_idx * 2),
        )
        db.add(app)
        db.flush()
        created += 1

        for i, (round_name, result) in enumerate(rounds):
            db.add(
                InterviewRound(
                    application_id=app.id,
                    round_name=round_name,
                    scheduled_on=start + timedelta(days=32 + s_idx * 2 + i * 3),
                    result=result,
                    feedback="Handled the questions well." if result == "passed" else None,
                )
            )

    placed = len({a[0] for a in APPLICATIONS if a[3] in ("offered", "joined")})
    print(f"  Placements: {len(companies)} companies, {created} applications, "
          f"{placed} of {len(students)} students placed")


def seed(reset: bool = False) -> None:
    db = SessionLocal()
    try:
        print("Seeding MOP Careers demo data...")
        if reset:
            reset_data(db)

        # --- admin --------------------------------------------------------
        upsert_user(db, name=ADMIN["name"], email=ADMIN["email"], password=ADMIN["password"],
                    role=ROLE_ADMIN, phone=ADMIN["phone"], must_change=False)
        print(f"  Admin:   {ADMIN['email']} / {ADMIN['password']}")

        # --- batch --------------------------------------------------------
        start = date.today() - timedelta(days=COMPLETED_THROUGH_DAY * 2)
        batch = db.scalar(select(Batch).where(Batch.name == BATCH_NAME))
        if batch is None:
            batch = Batch(name=BATCH_NAME)
            db.add(batch)
        batch.course_type = "Python Full Stack"
        batch.start_date = start
        batch.status = BATCH_ACTIVE
        db.flush()

        ensure_curriculum(db, batch.id)
        db.flush()
        print(f"  Batch:   {batch.name} (55 curriculum days)")

        # --- teacher ------------------------------------------------------
        teacher = upsert_user(db, name=TEACHER["name"], email=TEACHER["email"],
                              password=TEACHER["password"], role=ROLE_TEACHER,
                              phone=TEACHER["phone"], must_change=False)
        if not db.scalar(
            select(TeacherBatch).where(
                TeacherBatch.teacher_id == teacher.id, TeacherBatch.batch_id == batch.id
            )
        ):
            db.add(TeacherBatch(teacher_id=teacher.id, batch_id=batch.id))
        print(f"  Teacher: {TEACHER['email']} / {TEACHER['password']}  -> {batch.name}")

        # --- students -----------------------------------------------------
        students: list[User] = []
        for spec in STUDENTS:
            force = spec["email"] == FORCE_CHANGE_EMAIL
            s = upsert_user(db, name=spec["name"], email=spec["email"],
                            password=STUDENT_PASSWORD, role=ROLE_STUDENT,
                            phone=spec["phone"], must_change=force,
                            yoe_it=spec["yoe_it"], batch_id=batch.id)
            students.append(s)

            ms = db.scalar(select(Milestone).where(Milestone.student_id == s.id))
            if ms is None:
                ms = Milestone(student_id=s.id)
                db.add(ms)
            ms.enrolled = start - timedelta(days=10)
            ms.batch_assigned = start - timedelta(days=3)
            ms.batch_started = start
            db.flush()
        print(f"  Students: {len(students)} enrolled, password {STUDENT_PASSWORD}")
        print(f"            ({FORCE_CHANGE_EMAIL} must change password on first login)")

        # --- mark early days taught, with attendance ----------------------
        rng = random.Random(20260125)   # fixed seed keeps the demo reproducible
        days = db.scalars(
            select(CurriculumDay)
            .where(CurriculumDay.batch_id == batch.id)
            .order_by(CurriculumDay.day_number)
        ).all()

        for day in days:
            if day.day_number <= COMPLETED_THROUGH_DAY:
                day.scheduled_date = start + timedelta(days=(day.day_number - 1) * 2)
                day.status = DAY_COMPLETED
                day.recording_url = (
                    f"https://recordings.mopcareers.com/{batch.name.lower()}/day-{day.day_number}"
                )
                if not day.notes_file:
                    day.notes_file = make_notes_pdf(day.day_number, day.topic, batch.name)
            elif day.day_number <= COMPLETED_THROUGH_DAY + 6:
                # Next few classes get dates so the Schedule page has content.
                day.scheduled_date = start + timedelta(days=(day.day_number - 1) * 2)
        db.flush()

        completed_days = [d for d in days if d.day_number <= COMPLETED_THROUGH_DAY]
        existing = {
            (a.student_id, a.curriculum_day_id)
            for a in db.scalars(select(Attendance)).all()
        }
        marked = 0
        for student in students:
            for day in completed_days:
                if (student.id, day.id) in existing:
                    continue
                # ~85% present, so Missed Classes is not empty.
                db.add(
                    Attendance(
                        student_id=student.id,
                        curriculum_day_id=day.id,
                        present=rng.random() < 0.85,
                    )
                )
                marked += 1
        print(f"  Curriculum: days 1-{COMPLETED_THROUGH_DAY} marked complete "
              f"(recording links + notes PDFs), {marked} attendance records created")

        db.flush()
        seed_phase2(db, students, start)

        db.commit()
        print("\nSeed complete.")
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


